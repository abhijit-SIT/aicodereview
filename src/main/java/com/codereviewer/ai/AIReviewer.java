package com.codereviewer.ai;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import com.codereviewer.model.codeIssue;
import com.codereviewer.utils.PromptBuilder;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.stereotype.Component;

@Component
public class AIReviewer {

    private final String baseUrl;
    private final String model;
    private final int timeoutSeconds;
    private final HttpClient httpClient;
    private final ObjectMapper objectMapper;

    public AIReviewer() {
        this(
                resolveBaseUrl(),
                resolveModel(),
                resolveTimeout()
        );
    }

    public AIReviewer(String baseUrl, String model, int timeoutSeconds) {
        this.baseUrl = baseUrl.endsWith("/") ? baseUrl.substring(0, baseUrl.length() - 1) : baseUrl;
        this.model = model;
        this.timeoutSeconds = timeoutSeconds;
        this.httpClient = HttpClient.newBuilder()
                .connectTimeout(Duration.ofSeconds(10))
                .build();
        this.objectMapper = new ObjectMapper();
    }

    private static String resolveBaseUrl() {
        String env = System.getenv("OLLAMA_BASE_URL");
        if (env != null && !env.isBlank()) {
            return env.trim();
        }
        return System.getProperty("ollama.base-url", "http://localhost:11434");
    }

    private static String resolveModel() {
        String env = System.getenv("OLLAMA_MODEL");
        if (env != null && !env.isBlank()) {
            return env.trim();
        }
        return System.getProperty("ollama.model", "qwen2.5-coder:1.5b");
    }

    private static int resolveTimeout() {
        String env = System.getenv("OLLAMA_TIMEOUT_SECONDS");
        if (env != null && !env.isBlank()) {
            try {
                return Integer.parseInt(env.trim());
            } catch (NumberFormatException ignored) {}
        }
        String prop = System.getProperty("ollama.timeout-seconds");
        if (prop != null && !prop.isBlank()) {
            try {
                return Integer.parseInt(prop.trim());
            } catch (NumberFormatException ignored) {}
        }
        return 90;
    }

    /**
     * Checks whether Ollama is running and accessible.
     */
    public boolean isConfigured() {
        try {
            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(baseUrl + "/api/tags"))
                    .timeout(Duration.ofSeconds(4))
                    .GET()
                    .build();

            HttpResponse<String> response = httpClient.send(
                    request,
                    HttpResponse.BodyHandlers.ofString()
            );

            return response.statusCode() == 200;
        } catch (IOException e) {
            return false;
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            return false;
        }
    }

    /**
     * Sends Java source code and static-analysis findings
     * to PromptBuilder and then to Ollama.
     *
     * @param sourceCode Java source code being reviewed
     * @param staticIssues findings generated by static analyzers
     * @return AI-generated review
     */
    public String review(String sourceCode, List<codeIssue> staticIssues) {
        String prompt = PromptBuilder.build(sourceCode, staticIssues);
        return sendToOllama(prompt);
    }

    /**
     * Sends a prompt to the Ollama API with safe JSON serialization via Jackson.
     */
    private String sendToOllama(String prompt) {
        try {
            Map<String, Object> requestBody = new HashMap<>();
            requestBody.put("model", model);
            requestBody.put("prompt", prompt);
            requestBody.put("stream", false);

            String jsonPayload = objectMapper.writeValueAsString(requestBody);

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create(baseUrl + "/api/generate"))
                    .header("Content-Type", "application/json")
                    .timeout(Duration.ofSeconds(timeoutSeconds))
                    .POST(HttpRequest.BodyPublishers.ofString(jsonPayload))
                    .build();

            HttpResponse<String> response = httpClient.send(
                    request,
                    HttpResponse.BodyHandlers.ofString()
            );

            if (response.statusCode() != 200) {
                throw new RuntimeException("Ollama returned HTTP " + response.statusCode() + ": " + response.body());
            }

            JsonNode root = objectMapper.readTree(response.body());
            if (root.has("response")) {
                return root.get("response").asText();
            }
            if (root.has("error")) {
                throw new RuntimeException("Ollama error: " + root.get("error").asText());
            }

            return response.body();
        } catch (IOException e) {
            throw new RuntimeException("Could not connect to Ollama at " + baseUrl + " (" + e.getMessage() + ")", e);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new RuntimeException("Request to Ollama was interrupted.", e);
        }
    }

    public String getBaseUrl() {
        return baseUrl;
    }

    public String getModel() {
        return model;
    }

    public int getTimeoutSeconds() {
        return timeoutSeconds;
    }

    /**
     * CLI / Diagnostic testing method.
     */
    public static void main(String[] args) {
        AIReviewer reviewer = new AIReviewer();

        if (!reviewer.isConfigured()) {
            System.out.println("Ollama is not running at " + reviewer.getBaseUrl());
            return;
        }

        String sourceCode = """
                public class TestCode {
                    public void test() {
                        int a = 10;
                        int b = 0;
                        int result = a / b;
                        System.out.println(result);
                    }
                }
                """;

        try {
            String review = reviewer.review(sourceCode, List.of());
            System.out.println("========================================");
            System.out.println("          AI CODE REVIEW");
            System.out.println("========================================");
            System.out.println(review);
        } catch (RuntimeException e) {
            System.err.println("AI Reviewer Error: " + e.getMessage());
        }
    }
}