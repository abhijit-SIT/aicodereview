
package com.codereviewer.database;

import jakarta.annotation.PostConstruct;
import org.springframework.stereotype.Component;

import java.sql.Connection;
import java.sql.Statement;

@Component
public class DatabaseInitializer {

    @PostConstruct
    public void initializeDatabase() {

        String createReviewsTable = """
                CREATE TABLE IF NOT EXISTS reviews (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    file_name TEXT NOT NULL,
                    file_path TEXT,
                    review_date TEXT,
                    total_issues INTEGER,
                    ai_review TEXT
                )
                """;

        String createIssuesTable = """
                CREATE TABLE IF NOT EXISTS issues (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    review_id BIGINT NOT NULL,
                    rule TEXT,
                    severity TEXT,
                    line INTEGER,
                    message TEXT,
                    suggestion TEXT,
                    CONSTRAINT fk_issues_reviews
                        FOREIGN KEY (review_id)
                        REFERENCES reviews(id)
                        ON DELETE CASCADE
                )
                """;

        try (Connection connection = DatabaseManager.getConnection();
             Statement statement = connection.createStatement()) {

            statement.execute(createReviewsTable);
            statement.execute(createIssuesTable);

            System.out.println(
                    "PostgreSQL database initialized successfully."
            );

        } catch (Exception e) {

            System.err.println(
                    "Failed to initialize PostgreSQL database."
            );

            e.printStackTrace();

            // Fail startup instead of silently running without a schema.
            throw new IllegalStateException(
                    "PostgreSQL database initialization failed.", e
            );
        }
    }
}
